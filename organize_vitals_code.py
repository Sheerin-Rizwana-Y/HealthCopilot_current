"""Safely reorganize HealthCopilot's ml-model/vitals_risk code.

Run from the HealthCopilot repository root:
  python organize_vitals_code.py            # preview
  python organize_vitals_code.py --apply    # move files

Dataset locations are deliberately unchanged in this stage.
"""
from pathlib import Path
import argparse
import hashlib
import shutil
import sys

GROUPS = {
    "vitaldb": [
        "inspect_vitaldb.py",
        "inspect_vitaldb_cases.py",
        "download_vitaldb_sample.py",
        "inspect_sample_signals.py",
        "vitals_pipeline.py",
        "test_vitals_pipeline.py",
    ],
    "sepsis": [
        "download_sepsis.py",
        "split_sepsis.py",
        "preprocess_sepsis.py",
        "prepare_sepsis_temporal.py",
        "train_xgboost.py",
        "train_xgboost_temporal.py",
        "compare_temporal_models.py",
    ],
    "sepsis/drafts": ["train_sepsis.py"],  # empty in uploaded archive
}

DOC = """# Vitals ML — reorganized scripts

Work from the HealthCopilot repository root.

- `vitaldb/`: threshold-supervised physiological risk baseline and VitalDB utilities.
- `sepsis/`: research-only PhysioNet sepsis-label experiments; **not** Low/Moderate/High risk labels.
- `sepsis/drafts/train_sepsis.py`: unfinished, zero-byte file in the supplied archive.
- `baseline_5cases/`: original 5-case model archive (preserved).
- `artifacts/`: existing directory preserved.
- `requirements-phase2.txt`: existing requirements preserved.

Dataset folders under `datasets/vitals/` are **not moved** during this migration;
existing hard-coded dataset paths continue to work. A separate data-path migration
can be planned once the local dataset layout is inventoried.

VitalDB baseline commands:

```powershell
python ml-model/vitals_risk/vitaldb/vitals_pipeline.py prepare --raw datasets/vitals/raw --out datasets/vitals/processed
python ml-model/vitals_risk/vitaldb/vitals_pipeline.py train --out datasets/vitals/processed
python ml-model/vitals_risk/vitaldb/vitals_pipeline.py predict --out datasets/vitals/processed
python -m pytest -q ml-model/vitals_risk/vitaldb/test_vitals_pipeline.py
```

Sepsis experiment commands:

```powershell
python ml-model/vitals_risk/sepsis/prepare_sepsis_temporal.py
python ml-model/vitals_risk/sepsis/train_xgboost_temporal.py
python ml-model/vitals_risk/sepsis/compare_temporal_models.py
```

The `__pycache__/` folder is generated by Python and may be removed manually when
Python processes have stopped. It is not touched by this migration.
"""


def digest(p):
    h = hashlib.sha256()
    with p.open('rb') as f:
        for block in iter(lambda: f.read(1024 * 1024), b''):
            h.update(block)
    return h.digest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--apply', action='store_true', help='Actually move files (default: preview only)')
    args = parser.parse_args()
    root = Path.cwd() / 'ml-model' / 'vitals_risk'
    if not root.is_dir():
        sys.exit(f'ERROR: Cannot find {root}. Run from the HealthCopilot project root.')

    operations = []
    conflicts = []
    for subgroup, filenames in GROUPS.items():
        for name in filenames:
            src, dst = root / name, root / subgroup / name
            if src.is_file():
                if dst.exists():
                    conflicts.append(f'{src} -> {dst} (destination already exists)')
                else:
                    operations.append((src, dst))
            elif dst.exists():
                print(f'Already organized: {dst.relative_to(root)}')
            else:
                print(f'Not present; skipping: {name}')
    if conflicts:
        print('\nCONFLICTS — no changes made:')
        for item in conflicts: print('  ' + item)
        sys.exit(2)

    print(f'\nMode: {"APPLY" if args.apply else "PREVIEW (no changes)"}')
    for src, dst in operations:
        print(f'  {src.relative_to(root)}  ->  {dst.relative_to(root)}')
    print(f'\nFiles to move: {len(operations)}')
    print('Dataset files to move: 0 (paths unchanged)')
    print('Model artifacts to move: 0 (preserved)')

    if not args.apply:
        print('\nReview the plan, then run: python organize_vitals_code.py --apply')
        return

    for src, dst in operations:
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.move(str(src), str(dst))
    doc = root / 'STRUCTURE.md'
    if not doc.exists():
        doc.write_text(DOC, encoding='utf-8')
        print('Created:', doc.relative_to(Path.cwd()))
    else:
        print('Kept existing STRUCTURE.md unchanged')
    print('\nFinished. Next test:')
    print('  python -m pytest -q ml-model/vitals_risk/vitaldb/test_vitals_pipeline.py')


if __name__ == '__main__':
    main()
